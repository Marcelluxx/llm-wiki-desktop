export type Messages = (typeof messages)["it"];

export function getMessages(language: Language): Messages {
  return messages[language] as Messages;
}

export function formatAppError(reason: unknown, messages: Messages): string {
  const code =
    typeof reason === "object" && reason !== null && "code" in reason ? String(reason.code) : null;
  const localized: Record<string, string> = {
    empty_name: messages.errorEmptyName,
    relative_path: messages.errorRelativePath,
    missing_path: messages.errorMissingPath,
    not_directory: messages.errorNotDirectory,
    forbidden_root: messages.errorForbiddenRoot,
    duplicate_or_nested_path: messages.errorDuplicatePath,
    unknown_wiki: messages.errorUnknownWiki,
    io: messages.errorPermission,
    invalid_registry: messages.errorRegistry,
    unavailable: messages.errorGeneric,
    internal: messages.errorGeneric,
  };
  if (code && localized[code]) return localized[code];
  return reason instanceof Error ? reason.message : messages.errorGeneric;
}
